(() => {
  "use strict";
  let lang = "pl";
  try {
    const fromUrl = new URLSearchParams(location.search).get("lang");
    if (fromUrl === "pl" || fromUrl === "en") localStorage.setItem("prism-lang", fromUrl);
    lang = localStorage.getItem("prism-lang") === "en" ? "en" : "pl";
  } catch {
    /* brak localStorage — zostaje polski */
  }
  window.PRISM_LANG = lang;
  window.PRISM_APPLY_I18N = () => {};
  document.documentElement.lang = lang;
  if (lang === "pl") return;

  const ATTRS = ["placeholder", "aria-label", "content"];
  const apply = () => {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const text = window.PRISM_EN[el.dataset.i18n];
      if (text !== undefined) el.innerHTML = text;
    });
    ATTRS.forEach((attr) => {
      document.querySelectorAll(`[data-i18n-${attr}]`).forEach((el) => {
        const text = window.PRISM_EN[el.getAttribute(`data-i18n-${attr}`)];
        if (text !== undefined) el.setAttribute(attr, text);
      });
    });
  };
  // <head> tłumaczymy od razu; treść strony tłumaczy script.js na starcie
  // (stoi na końcu <body>, więc wykonuje się przed DOMContentLoaded)
  apply();
  window.PRISM_APPLY_I18N = apply;
})();
